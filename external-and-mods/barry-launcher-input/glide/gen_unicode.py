#!/usr/bin/env python3
"""Writes unicode_tables.inc: the character facts barry_glide.py gets from
Python's str methods (isalpha, isupper, isspace, lower, upper, int()'s
digits and lower()'s final sigma), so barryglide decides exactly as the
Python it replaces. Run it with the device's Python (the rootfs's, through
bwrap; see build.sh) whenever that Python's Unicode version changes:

    python3 gen_unicode.py > unicode_tables.inc
"""
import sys
import unicodedata

MAX = 0x110000


def chars():
    for cp in range(MAX):
        if 0xD800 <= cp <= 0xDFFF:
            continue  # never in valid UTF-8
        yield cp, chr(cp)


def ranges(pred):
    out, start, prev = [], None, None
    for cp, c in chars():
        if pred(cp, c):
            if start is None:
                start = cp
            elif prev != cp - 1:
                out.append((start, prev))
                start = cp
            prev = cp
        elif start is not None:
            out.append((start, prev))
            start = None
    if start is not None:
        out.append((start, prev))
    return out


SIGMA = "Σ"


def final_after(x):
    """Σ right after x: final (ς) iff x is cased and not case-ignorable."""
    return (x + SIGMA).lower()[-1] == "ς"


def final_after_a(x):
    """Σ after "A" + x: final iff x is case-ignorable or cased."""
    return ("A" + x + SIGMA).lower()[-1] == "ς"


def emit_ranges(name, rs):
    print(f"static const Range {name}[] = {{")
    for i in range(0, len(rs), 6):
        print("    " + " ".join(f"{{0x{a:X}, 0x{b:X}}}," for a, b in rs[i:i + 6]))
    print("};")


def lit(s):
    return "U\"" + "".join(f"\\U{ord(c):08X}" for c in s) + "\""


def emit_map(name, items):
    print(f"static const Mapping {name}[] = {{")
    for cp, s in items:
        print(f"    {{0x{cp:X}, {lit(s)}}},")
    print("};")


def main():
    print(f"// Generated by gen_unicode.py from Python {sys.version.split()[0]}"
          f" (Unicode {unicodedata.unidata_version}). Do not edit.")
    emit_ranges("ALPHA", ranges(lambda cp, c: c.isalpha()))
    emit_ranges("UPPER", ranges(lambda cp, c: c.isupper()))
    emit_ranges("SPACE", ranges(lambda cp, c: c.isspace()))
    emit_ranges("CASE_IGNORABLE", ranges(lambda cp, c: final_after_a(c) and not final_after(c)))
    emit_ranges("CASED", ranges(lambda cp, c: final_after(c)))
    emit_map("LOWER", [(cp, c.lower()) for cp, c in chars() if c.lower() != c and c != SIGMA])
    emit_map("UPPERMAP", [(cp, c.upper()) for cp, c in chars() if c.upper() != c])
    # int()'s digits: runs of consecutive decimal values.
    runs, start, prev, base = [], None, None, 0
    for cp, c in chars():
        d = unicodedata.decimal(c, None)
        if d is not None and start is not None and prev == cp - 1 and d == base + cp - start:
            prev = cp
            continue
        if start is not None:
            runs.append((start, prev, base))
            start = None
        if d is not None:
            start, prev, base = cp, cp, d
    if start is not None:
        runs.append((start, prev, base))
    print("static const DigitRun DECIMAL[] = {")
    for a, b, v in runs:
        print(f"    {{0x{a:X}, 0x{b:X}, {v}}},")
    print("};")


main()
